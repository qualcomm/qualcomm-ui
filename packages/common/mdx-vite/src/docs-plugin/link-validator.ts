import chalk from "chalk"
import type {Link, Root} from "mdast"
import type {
  MdxJsxAttribute,
  MdxJsxFlowElement,
  MdxJsxTextElement,
} from "mdast-util-mdx-jsx"
import {statSync} from "node:fs"
import {posix, resolve, sep} from "node:path"
import {visit} from "unist-util-visit"

import type {PageMap} from "@qualcomm-ui/mdx-common"

import type {LintSeverity} from "./config/index.js"
import {
  isMdxFileLink,
  type MdxFileLinkOptions,
  resolveMdxFileLink,
} from "./mdx-file-links.js"
import {realPath} from "./path-utils.js"

export interface CollectedLink {
  /**
   * Whether the link was authored as a relative path to an `.mdx` file.
   */
  fileLink?: boolean
  fragment?: string
  sourceFile: string
  sourcePathname: string
  targetPathname: string
  url: string
}

export interface InvalidLink extends CollectedLink {
  reason: "fragment-not-found" | "page-not-found"
}

export interface FileLinkIssue extends CollectedLink {
  /**
   * Equivalent link that uses a relative `.mdx` file path.
   */
  suggestion: string
}

const externalPrefixes = ["https://", "http://", "mailto:", "tel:"]

function isExternal(url: string): boolean {
  return externalPrefixes.some((prefix) => url.startsWith(prefix))
}

/**
 * Resolves a raw markdown link URL into a pathname and optional fragment.
 * Returns null for external links that should be skipped.
 */
export function resolveLink(
  url: string,
  sourcePathname: string,
): {fragment?: string; pathname: string} | null {
  if (isExternal(url)) {
    return null
  }

  const [rawPath, fragment] = url.split("#", 2)

  let pathname: string
  if (!rawPath || rawPath === "./" || rawPath === ".") {
    pathname = sourcePathname
  } else if (rawPath.startsWith("/")) {
    pathname = rawPath
  } else {
    // Relative path — resolve against the source page's "directory"
    const sourceDir = sourcePathname.endsWith("/")
      ? sourcePathname
      : posix.dirname(sourcePathname)
    pathname = posix.resolve(sourceDir, rawPath)
  }

  // Normalize trailing slashes
  if (pathname !== "/" && pathname.endsWith("/")) {
    pathname = pathname.slice(0, -1)
  }

  return {fragment: fragment || undefined, pathname}
}

/**
 * Walks the AST and collects all internal links from a parsed MDX page. When
 * `fileLinkOptions` is provided, relative `.mdx` file links resolve against
 * `sourceFile` instead of the page URL.
 */
export function collectLinks(
  tree: Root,
  sourceFile: string,
  sourcePathname: string,
  fileLinkOptions?: MdxFileLinkOptions,
): CollectedLink[] {
  const links: CollectedLink[] = []
  const realSourceFile = fileLinkOptions ? realPath(sourceFile) : sourceFile

  visit(tree, "link", (node: Link) => {
    const fileLink = !!fileLinkOptions && isMdxFileLink(node.url)
    const resolved =
      (fileLink &&
        resolveMdxFileLink(node.url, realSourceFile, fileLinkOptions)) ||
      resolveLink(node.url, sourcePathname)
    if (!resolved) {
      return
    }

    links.push({
      fileLink: fileLink || undefined,
      fragment: resolved.fragment,
      sourceFile,
      sourcePathname,
      targetPathname: resolved.pathname,
      url: node.url,
    })
  })

  return links
}

function getLiteralAttributeValue(
  node: MdxJsxFlowElement | MdxJsxTextElement,
  name: string,
): string | undefined {
  const attr = node.attributes.find(
    (attribute): attribute is MdxJsxAttribute =>
      attribute.type === "mdxJsxAttribute" && attribute.name === name,
  )

  return typeof attr?.value === "string" ? attr.value : undefined
}

/**
 * Walks the MDX AST and collects explicit HTML anchor IDs that can be used as
 * fragment targets but should not appear in the page ToC.
 */
export function collectAnchorIds(tree: Root): Set<string> {
  const anchorIds = new Set<string>()

  const collectAnchorId = (node: MdxJsxFlowElement | MdxJsxTextElement) => {
    if (node.name !== "a") {
      return
    }

    const id = getLiteralAttributeValue(node, "id")
    if (id) {
      anchorIds.add(id)
    }
  }

  visit(tree, "mdxJsxFlowElement", collectAnchorId)
  visit(tree, "mdxJsxTextElement", collectAnchorId)

  return anchorIds
}

/**
 * Whether the pathname refers to a file in the Vite public directory. Vite serves
 * these files at the site root, so they are valid link targets without a page.
 */
export function isPublicFile(publicDir: string, pathname: string): boolean {
  let decoded: string
  try {
    decoded = decodeURIComponent(pathname)
  } catch {
    return false
  }

  const root = resolve(publicDir)
  const filePath = resolve(root, `.${posix.normalize(decoded)}`)
  if (!filePath.startsWith(`${root}${sep}`)) {
    return false
  }

  return !!statSync(filePath, {throwIfNoEntry: false})?.isFile()
}

/**
 * Validates collected links against the fully assembled page map.
 * The optional ID maps provide additional valid fragment targets generated by
 * TypeDocProps or explicit MDX anchor elements on each page. Links that resolve
 * to a file in `publicDir` are treated as valid.
 */
export function validateLinks(
  links: CollectedLink[],
  pageMap: PageMap,
  docPropIds?: Record<string, Set<string>>,
  anchorIds?: Record<string, Set<string>>,
  publicDir?: string,
): InvalidLink[] {
  const invalid: InvalidLink[] = []

  for (const link of links) {
    const page = pageMap[link.targetPathname]

    if (!page) {
      if (publicDir && isPublicFile(publicDir, link.targetPathname)) {
        continue
      }
      invalid.push({...link, reason: "page-not-found"})
      continue
    }

    if (link.fragment) {
      const inToc = page.toc?.some((h) => h.id === link.fragment)
      const inDocProps = docPropIds?.[link.targetPathname]?.has(link.fragment)
      const inAnchorIds = anchorIds?.[link.targetPathname]?.has(link.fragment)
      if (!inToc && !inDocProps && !inAnchorIds) {
        invalid.push({...link, reason: "fragment-not-found"})
      }
    }
  }

  return invalid
}

/**
 * Returns the relative `.mdx` file path equivalent of a URL-path link to an MDX
 * page, like `../button+/_button.mdx#size` for `/components/button#size`, or
 * `#size` for `./#size` on the same page. Returns null for file links, bare
 * fragments, and links to TSX pages, public files, or missing pages, which have
 * no `.mdx` file equivalent.
 *
 * @param pageFiles MDX source file path for each page pathname.
 */
export function getFileLinkSuggestion(
  link: Pick<
    CollectedLink,
    | "fileLink"
    | "fragment"
    | "sourceFile"
    | "sourcePathname"
    | "targetPathname"
    | "url"
  >,
  pageFiles: Record<string, string>,
): string | null {
  if (link.fileLink || link.url.startsWith("#")) {
    return null
  }

  const fragment = link.fragment ? `#${link.fragment}` : ""

  if (link.targetPathname === link.sourcePathname && fragment) {
    return fragment
  }

  const targetFile = pageFiles[link.targetPathname]
  if (!targetFile) {
    return null
  }

  const relativePath = encodeURI(
    posix.relative(posix.dirname(link.sourceFile), targetFile),
  )
  const filePath = relativePath.startsWith("../")
    ? relativePath
    : `./${relativePath}`
  return `${filePath}${fragment}`
}

/**
 * Finds internal links to MDX pages that use URL paths, like `/components/button`
 * or `./#size`, instead of relative file paths. URL paths don't resolve in
 * GitHub's markdown viewer.
 *
 * @param pageFiles MDX source file path for each page pathname.
 */
export function findNonFileLinks(
  links: CollectedLink[],
  pageFiles: Record<string, string>,
): FileLinkIssue[] {
  const issues: FileLinkIssue[] = []

  for (const link of links) {
    const suggestion = getFileLinkSuggestion(link, pageFiles)
    if (suggestion) {
      issues.push({...link, suggestion})
    }
  }

  return issues
}

/**
 * Logs links reported by {@link findNonFileLinks} grouped by source page.
 */
export function reportFileLinkIssues(
  issues: FileLinkIssue[],
  severity: LintSeverity = "warn",
): void {
  if (issues.length === 0) {
    return
  }

  const grouped = new Map<string, FileLinkIssue[]>()
  for (const issue of issues) {
    const existing = grouped.get(issue.sourcePathname) ?? []
    existing.push(issue)
    grouped.set(issue.sourcePathname, existing)
  }

  const color = severity === "error" ? chalk.redBright : chalk.yellowBright
  console.debug(
    `\n${color.bold(`Found ${issues.length} link${issues.length === 1 ? "" : "s"} that should use a relative .mdx file path:`)}`,
  )

  for (const [sourcePathname, pageIssues] of grouped) {
    console.debug(`\n  ${chalk.blueBright.bold(sourcePathname)}`)
    for (const issue of pageIssues) {
      console.debug(
        `    ${chalk.red("x")} ${issue.url} — use ${chalk.greenBright(issue.suggestion)}`,
      )
    }
  }

  console.debug(
    `\nRun ${chalk.cyanBright("qui-docs fix-links")} to apply these replacements, or ${chalk.cyanBright("qui-docs fix-links --dry-run")} to preview them.`,
  )
  console.debug("")
}

/**
 * Logs invalid links to the console grouped by source page.
 */
export function reportInvalidLinks(
  invalidLinks: InvalidLink[],
  severity: LintSeverity = "warn",
): void {
  if (invalidLinks.length === 0) {
    return
  }

  const grouped = new Map<string, InvalidLink[]>()
  for (const link of invalidLinks) {
    const existing = grouped.get(link.sourcePathname) ?? []
    existing.push(link)
    grouped.set(link.sourcePathname, existing)
  }

  const color = severity === "error" ? chalk.redBright : chalk.yellowBright
  console.debug(
    `\n${color.bold(`Found ${invalidLinks.length} broken link${invalidLinks.length === 1 ? "" : "s"}:`)}`,
  )

  for (const [sourcePathname, links] of grouped) {
    console.debug(`\n  ${chalk.blueBright.bold(sourcePathname)}`)
    for (const link of links) {
      const reason =
        link.reason === "page-not-found"
          ? "page not found"
          : `fragment "#${link.fragment}" not found`
      console.debug(`    ${chalk.red("x")} ${link.url} — ${reason}`)
    }
  }

  console.debug("")
}
